import React, { useState, useEffect } from 'react';
import { Link } from 'react-router-dom';
import { roadmapService, jobService } from '../services/api';
import { CardSkeleton } from '../components/SkeletonLoader';
import EmptyState from '../components/EmptyState';
import toast from 'react-hot-toast';
import {
  Compass,
  Sparkles,
  ArrowRight,
  Clock,
  Calendar,
  CheckCircle2,
  Trash2,
  Plus,
  Loader2,
  X
} from 'lucide-react';

const Roadmaps = () => {
  const [roadmaps, setRoadmaps] = useState([]);
  const [jobs, setJobs] = useState([]);
  const [loading, setLoading] = useState(true);

  // Modal for new roadmap
  const [isModalOpen, setIsModalOpen] = useState(false);
  const [selectedJobId, setSelectedJobId] = useState('');
  const [totalWeeks, setTotalWeeks] = useState(4);
  const [hoursPerWeek, setHoursPerWeek] = useState(10);
  const [generating, setGenerating] = useState(false);

  const fetchRoadmaps = async () => {
    setLoading(true);
    try {
      const [roadmapsRes, jobsRes] = await Promise.all([
        roadmapService.getRoadmaps(),
        jobService.getJobs(),
      ]);
      setRoadmaps(roadmapsRes.data.roadmaps || []);
      setJobs(jobsRes.data.jobs || []);
      if (jobsRes.data.jobs?.length > 0) {
        setSelectedJobId(jobsRes.data.jobs[0].id);
      }
    } catch (err) {
      console.error('Failed to load roadmaps:', err);
      toast.error('Failed to load learning roadmaps.');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchRoadmaps();
  }, []);

  const handleGenerate = async (e) => {
    e.preventDefault();
    if (!selectedJobId) {
      toast.error('Please select an analyzed job.');
      return;
    }

    setGenerating(true);
    try {
      const res = await roadmapService.generateRoadmap({
        jobAnalysisId: selectedJobId,
        totalWeeks: parseInt(totalWeeks),
        hoursPerWeek: parseInt(hoursPerWeek),
      });
      toast.success('AI Learning Roadmap synthesized!');
      setIsModalOpen(false);
      fetchRoadmaps();
    } catch (err) {
      const msg = err.response?.data?.error || 'Failed to generate roadmap.';
      toast.error(msg);
    } finally {
      setGenerating(false);
    }
  };

  const handleDelete = async (id, title) => {
    if (!window.confirm(`Delete roadmap: ${title}?`)) return;
    try {
      await roadmapService.deleteRoadmap(id);
      toast.success('Roadmap deleted.');
      setRoadmaps(roadmaps.filter((r) => r.id !== id));
    } catch {
      toast.error('Failed to delete roadmap.');
    }
  };

  return (
    <div className="space-y-8 font-sans">
      {/* Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <h2 className="text-xl font-bold text-slate-900 tracking-tight">Personalized AI Learning Roadmaps</h2>
          <p className="text-xs text-slate-500">
            Structured week-by-week curricula dynamically generated by Gemini AI to eliminate your specific skill gaps.
          </p>
        </div>

        <button
          onClick={() => setIsModalOpen(true)}
          className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl font-bold text-xs text-white bg-gradient-to-r from-brand-600 to-indigo-600 hover:shadow-glow hover:scale-[1.02] transition-all"
        >
          <Sparkles className="w-4 h-4 text-cyan-300" />
          <span>Synthesize New Roadmap</span>
        </button>
      </div>

      {/* Roadmaps Grid */}
      {loading ? (
        <CardSkeleton count={3} />
      ) : roadmaps.length > 0 ? (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
          {roadmaps.map((r) => {
            const progress = Math.round(parseFloat(r.progress) || 0);

            return (
              <div
                key={r.id}
                className="bg-white p-6 rounded-3xl border border-slate-200/80 shadow-card hover:shadow-premium transition-all flex flex-col justify-between"
              >
                <div>
                  <div className="flex items-start justify-between mb-3">
                    <span className={`text-[10px] font-extrabold uppercase tracking-wider px-2.5 py-0.5 rounded-full ${
                      r.status === 'completed'
                        ? 'bg-emerald-50 text-emerald-700 border border-emerald-200'
                        : 'bg-brand-50 text-brand-700 border border-brand-200'
                    }`}>
                      {r.status === 'completed' ? 'Completed' : 'Active Plan'}
                    </span>

                    <button
                      onClick={() => handleDelete(r.id, r.title)}
                      className="text-slate-400 hover:text-rose-600 transition-colors"
                      title="Delete roadmap"
                    >
                      <Trash2 className="w-4 h-4" />
                    </button>
                  </div>

                  <h3 className="text-base font-bold text-slate-900 mb-1 leading-snug">{r.title}</h3>
                  <p className="text-xs text-slate-500 mb-4">{r.job_title || 'General Development'}</p>

                  {/* Progress Bar */}
                  <div className="space-y-1.5 mb-5">
                    <div className="flex items-center justify-between text-xs font-semibold">
                      <span className="text-slate-600">Overall Progress</span>
                      <span className="font-mono text-brand-600">{progress}%</span>
                    </div>
                    <div className="w-full h-2 rounded-full bg-slate-100 overflow-hidden">
                      <div
                        className="h-full bg-gradient-to-r from-brand-600 to-cyan-500 rounded-full transition-all duration-500"
                        style={{ width: `${progress}%` }}
                      ></div>
                    </div>
                  </div>

                  {/* Metadata pills */}
                  <div className="grid grid-cols-2 gap-2 text-xs mb-4">
                    <div className="p-2.5 rounded-xl bg-slate-50 border border-slate-100 flex items-center gap-2">
                      <Calendar className="w-3.5 h-3.5 text-slate-400" />
                      <span className="font-semibold text-slate-700">{r.total_weeks} Weeks</span>
                    </div>
                    <div className="p-2.5 rounded-xl bg-slate-50 border border-slate-100 flex items-center gap-2">
                      <Clock className="w-3.5 h-3.5 text-slate-400" />
                      <span className="font-semibold text-slate-700">{Math.round(r.total_hours)} Hours</span>
                    </div>
                  </div>
                </div>

                <div className="pt-4 border-t border-slate-100 flex items-center justify-between">
                  <span className="text-[11px] font-semibold text-slate-500">
                    {r.completed_tasks || 0} / {r.total_tasks || 0} Tasks Done
                  </span>

                  <Link
                    to={`/roadmaps/${r.id}`}
                    className="inline-flex items-center gap-1.5 px-4 py-2 rounded-xl font-bold text-xs bg-slate-900 text-white hover:bg-brand-600 transition-colors"
                  >
                    <span>View Curriculum</span>
                    <ArrowRight className="w-3.5 h-3.5" />
                  </Link>
                </div>
              </div>
            );
          })}
        </div>
      ) : (
        <EmptyState
          icon={Compass}
          title="No roadmaps synthesized yet"
          description="Create your first tailored learning roadmap to systematically master the technical skills needed for your target career."
          actionLabel="Generate First Roadmap"
          onAction={() => setIsModalOpen(true)}
        />
      )}

      {/* Synthesis Modal */}
      {isModalOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/70 backdrop-blur-sm animate-in fade-in">
          <div className="bg-white w-full max-w-lg rounded-3xl p-6 sm:p-8 shadow-premium border border-slate-200">
            <div className="flex items-center justify-between pb-4 border-b border-slate-100">
              <div className="flex items-center gap-2.5">
                <div className="p-2 rounded-xl bg-brand-50 text-brand-600">
                  <Sparkles className="w-5 h-5" />
                </div>
                <div>
                  <h3 className="text-base font-bold text-slate-900">Synthesize AI Learning Roadmap</h3>
                  <p className="text-xs text-slate-500">Powered by Google Gemini 1.5</p>
                </div>
              </div>
              <button
                onClick={() => setIsModalOpen(false)}
                className="p-1.5 text-slate-400 hover:text-slate-700 rounded-lg"
              >
                <X className="w-5 h-5" />
              </button>
            </div>

            <form onSubmit={handleGenerate} className="mt-5 space-y-4">
              <div>
                <label className="block text-xs font-bold uppercase text-slate-700 mb-2">
                  Target Job Analysis *
                </label>
                {jobs.length > 0 ? (
                  <select
                    value={selectedJobId}
                    onChange={(e) => setSelectedJobId(e.target.value)}
                    className="w-full p-3 rounded-xl border border-slate-300 text-xs font-semibold focus:ring-2 focus:ring-brand-500"
                    required
                  >
                    {jobs.map((j) => (
                      <option key={j.id} value={j.id}>
                        {j.job_title} ({j.company_name || 'Employer'})
                      </option>
                    ))}
                  </select>
                ) : (
                  <p className="text-xs text-rose-600">
                    No analyzed jobs found. Please analyze a job description first.
                  </p>
                )}
              </div>

              <div className="grid grid-cols-2 gap-4">
                <div>
                  <label className="block text-xs font-bold uppercase text-slate-700 mb-2">
                    Total Duration (Weeks)
                  </label>
                  <select
                    value={totalWeeks}
                    onChange={(e) => setTotalWeeks(e.target.value)}
                    className="w-full p-3 rounded-xl border border-slate-300 text-xs font-semibold"
                  >
                    <option value="2">2 Weeks (Crash Course)</option>
                    <option value="4">4 Weeks (Standard)</option>
                    <option value="6">6 Weeks (In-Depth)</option>
                    <option value="8">8 Weeks (Comprehensive)</option>
                  </select>
                </div>

                <div>
                  <label className="block text-xs font-bold uppercase text-slate-700 mb-2">
                    Study Hours / Week
                  </label>
                  <select
                    value={hoursPerWeek}
                    onChange={(e) => setHoursPerWeek(e.target.value)}
                    className="w-full p-3 rounded-xl border border-slate-300 text-xs font-semibold"
                  >
                    <option value="5">5 Hours (Casual)</option>
                    <option value="10">10 Hours (Balanced)</option>
                    <option value="15">15 Hours (Dedicated)</option>
                    <option value="25">25+ Hours (Bootcamp)</option>
                  </select>
                </div>
              </div>

              <div className="pt-4 flex items-center justify-end gap-3 border-t border-slate-100">
                <button
                  type="button"
                  onClick={() => setIsModalOpen(false)}
                  className="px-4 py-2.5 rounded-xl text-xs font-bold text-slate-600 hover:bg-slate-100"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  disabled={generating || jobs.length === 0}
                  className="inline-flex items-center gap-2 px-6 py-3 rounded-xl font-bold text-xs text-white bg-gradient-to-r from-brand-600 to-indigo-600 hover:shadow-glow disabled:opacity-50"
                >
                  {generating ? (
                    <>
                      <Loader2 className="w-4 h-4 animate-spin text-white" />
                      <span>Synthesizing Curriculum...</span>
                    </>
                  ) : (
                    <>
                      <Sparkles className="w-4 h-4 text-cyan-300" />
                      <span>Generate Roadmap</span>
                    </>
                  )}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
};

export default Roadmaps;
